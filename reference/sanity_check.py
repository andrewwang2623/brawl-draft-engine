"""Sanity check: our Legendary+ post-patch brawler strengths vs AshBS's overall tier list.
NOT used for training. Writes reference/SANITY_CHECK.md.

    .venv/bin/python reference/sanity_check.py
"""
import csv
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from data import load_matches  # noqa: E402
from model import DraftModel, model_path  # noqa: E402

TIERS = "SABCDF"
TVAL = {t: 5 - i for i, t in enumerate(TIERS)}       # S=5 ... F=0
THIN_GAMES = 500
PATCH_NOTES = {
    "buff": ["Hank", "Shelly", "Ziggy", "Draco", "Chuck", "Darryl", "Melodie", "Buster", "Angelo", "R-T"],
    "nerf": ["Amber", "Shade", "Gus", "Wendy", "Colette", "Ash", "Max", "Pierce", "Maisie", "Nori", "Brock", "Rico"],
    "change": ["Surge", "Cosmo", "Damian", "Squeak", "Kit"],
    "rework / new buffies": ["Lou", "Gale", "Mandy", "Chester", "Berry", "Mr. P"],
    "new hypercharge": ["Cosmo", "Vince"],
    "brawl arena only": ["Ollie", "Janet", "Gray", "Gigi", "Stu", "Starr Nova", "8-Bit", "Mandy", "Piper",
                         "Nori", "Fang", "Najia", "Doug", "Chuck"],
}
MODE_NAMES = {"brawlBall": "Brawl Ball", "gemGrab": "Gem Grab", "knockout": "Knockout",
              "bounty": "Bounty", "heist": "Heist", "hotZone": "Hot Zone"}


def to_tiers(scores: dict, sizes: dict) -> dict:
    """Assign our tiers by rank, using the same tier sizes as Ash's list."""
    order = sorted(scores, key=lambda b: -scores[b])
    out, i = {}, 0
    for t in TIERS:
        for b in order[i:i + sizes[t]]:
            out[b] = t
        i += sizes[t]
    return out


def main():
    md = DraftModel.load(model_path("legendary"))
    m = load_matches()
    target = md.in_target(m)
    m = m.subset(np.flatnonzero(target))
    name = {int(b): v["name"] for b, v in md.meta.items()}
    by_name = {v: k for k, v in name.items()}

    ash = {r["brawler"]: r for r in csv.DictReader(open(ROOT / "reference" / "ashbs_tiers.csv"))}
    ash = {b: r for b, r in ash.items() if not r["source_confidence"].startswith("unreleased")}

    # raw stats (Legendary+ post-patch)
    games, wins = defaultdict(int), defaultdict(float)
    mode_games = defaultdict(int)
    for i in range(len(m)):
        for team, won in ((m.team_a[i], m.y[i]), (m.team_b[i], 1 - m.y[i])):
            for x in team:
                games[int(x)] += 1
                wins[int(x)] += won
                mode_games[(m.mode[i], int(x))] += 1
    n_games = len(m)

    # model strength: games-weighted mean of S over the current map pool, overall and per mode
    maps = md.known_maps()
    ids = md.brawler_ids()
    overall = np.zeros(len(ids))
    per_mode = defaultdict(lambda: np.zeros(len(ids)))
    mode_tot = defaultdict(int)
    tot = 0
    for mode, mp, c in maps:
        S = md.map_model(mp, mode).S
        overall += S * c
        per_mode[mode] += S * c
        mode_tot[mode] += c
        tot += c
    overall /= tot
    for k in per_mode:
        per_mode[k] /= mode_tot[k]
    idx = {int(b): i for i, b in enumerate(ids)}

    common = [b for b in ash if b in by_name and games.get(by_name[b], 0) > 0]
    no_data = [b for b in ash if b not in common]
    ours = {b: overall[idx[by_name[b]]] for b in common}
    sizes = {t: sum(1 for b in common if ash[b]["tier"] == t) for t in TIERS}
    our_tier = to_tiers(ours, sizes)
    mode_tier = {mode: to_tiers({b: per_mode[mode][idx[by_name[b]]] for b in common}, sizes)
                 for mode in per_mode}

    ash_v = [TVAL[ash[b]["tier"]] for b in common]
    rho, p = spearmanr([ours[b] for b in common], ash_v)
    wr = {b: wins[by_name[b]] / games[by_name[b]] for b in common}
    pr = {b: games[by_name[b]] / n_games for b in common}
    rho_wr, _ = spearmanr([wr[b] for b in common], ash_v)
    rho_pr, _ = spearmanr([pr[b] for b in common], ash_v)
    big = [b for b in common if np.mean(m.ts) and abs(TVAL[our_tier[b]] - TVAL[ash[b]["tier"]]) >= 2]
    rho_by_mode = {mode: spearmanr([per_mode[mode][idx[by_name[b]]] for b in common], ash_v)[0]
                   for mode in per_mode}

    L = []
    w = L.append
    w("# Sanity check: our model vs AshBS's overall tier list (Nov 2026)\n")
    w("_Reference only. The tier list is **not** used for training. Generated by "
      "`reference/sanity_check.py`._\n")
    w(f"- Our data: **{n_games:,} Legendary+ post-patch games** (patch 2026-11-03 09:00 UTC), "
      f"{len(maps)} maps. Model: `models/model_legendary.pkl` (trained on {md.n_train:,} games).")
    w("- **Our overall strength** = each brawler's map-strength term S (global + mode + map + class "
      "terms; teammates and opponents are controlled for), averaged over the current ranked map pool "
      "and weighted by games per map. Synergy and counter terms are excluded.")
    w(f"- Compared: {len(common)} released brawlers on both lists. Thunder Frogs (unreleased), Rey and "
      f"Ruby (new, not on the list and not seen in data) are excluded."
      + (f" On the list but never seen in our games: {', '.join(no_data)}." if no_data else ""))
    w("- \"Our tier\" ranks our strengths and cuts them into tiers using the same tier sizes as "
      f"Ash's list ({', '.join(f'{t}={sizes[t]}' for t in TIERS)}).\n")

    w("## Correlation (Spearman, vs Ash tier S=5 … F=0)\n")
    w("| signal | ρ |\n|---|---|")
    w(f"| **our model's overall strength** | **{rho:.2f}** (p={p:.1g}) |")
    w(f"| raw win rate (Legendary+ post-patch) | {rho_wr:.2f} |")
    w(f"| pick rate (Legendary+ post-patch) | {rho_pr:.2f} |")
    for mode in sorted(rho_by_mode):
        w(f"| our strength in {MODE_NAMES.get(mode, mode)} only | {rho_by_mode[mode]:.2f} |")
    w("")
    w("Reading: pick rate measures what top players *think* is strong, which is also what a tier list "
      f"captures, so it tracks Ash closely (ρ={rho_pr:.2f}). Win rate and our model measure what actually "
      f"wins in Legendary+ since the patch, and they barely relate to Ash's tiers (ρ={rho:.2f} model, "
      f"{rho_wr:.2f} raw). Ash's list was made hours after the patch, before results existed. "
      "See \"What explains the gap\" below.\n")

    # Patch-category breakdown of raw outcomes
    w("## What explains the gap\n")
    cats = {"nerfed": PATCH_NOTES["nerf"], "reworked / new buffies": PATCH_NOTES["rework / new buffies"],
            "buffed": PATCH_NOTES["buff"]}
    other = [b for b in common if not any(b in v for v in cats.values())]
    cats["unchanged (not in notes)"] = other
    w("| group (patch notes) | brawlers | games | pooled raw win rate | mean Ash tier | mean our tier |\n|---|---|---|---|---|---|")
    for cat, bs in cats.items():
        bs = [b for b in bs if b in common]
        g = sum(games[by_name[b]] for b in bs)
        wsum = sum(wins[by_name[b]] for b in bs)
        w(f"| {cat} | {len(bs)} | {g:,} | {100 * wsum / g:.1f}% | "
          f"{np.mean([TVAL[ash[b]['tier']] for b in bs]):.1f} | {np.mean([TVAL[our_tier[b]] for b in bs]):.1f} |")
    lo = [b for b in common if pr[b] < 0.02]
    hi = [b for b in common if pr[b] >= 0.08]
    def pooled(bs):
        return 100 * sum(wins[by_name[b]] for b in bs) / max(1, sum(games[by_name[b]] for b in bs))
    w(f"| pick rate < 2% (niche) | {len(lo)} | {sum(games[by_name[b]] for b in lo):,} | {pooled(lo):.1f}% | "
      f"{np.mean([TVAL[ash[b]['tier']] for b in lo]):.1f} | {np.mean([TVAL[our_tier[b]] for b in lo]):.1f} |")
    w(f"| pick rate ≥ 8% (meta) | {len(hi)} | {sum(games[by_name[b]] for b in hi):,} | {pooled(hi):.1f}% | "
      f"{np.mean([TVAL[ash[b]['tier']] for b in hi]):.1f} | {np.mean([TVAL[our_tier[b]] for b in hi]):.1f} |")
    w("")
    w("Likely causes, in rough order of how much they explain:")
    w("1. **The patch is real and recent, and the tier list predates its results.** Buffed brawlers "
      "pool at a clearly winning rate, and we rank the nerfed group far lower than Ash does. Several heavily "
      "picked nerfed or reworked brawlers lose badly (Shade, Max, Pierce, Wendy, Berry: 41–45% on "
      "thousands of games each). As a group they pool near 50% only because Brock and Rico still hold up. "
      "The reworks gave *new* Buffies that most players don't own yet; you're missing them on exactly "
      "those brawlers. Ash rates fully built kits; our data reflects what people actually bring.")
    w("2. **Popularity vs. results at the bottom of the list.** Niche brawlers (< 2% pick rate) pool at "
      "about 50% in aggregate. They're not losing, just unpopular. Ash's D/F tiers are mostly unpopular "
      "brawlers, while our numbers put many of them mid-pack or above. Individual high niche win rates "
      "can still come from draft selection (picked last *because* they counter) or one-trick specialists. "
      "Our counter terms are heavily shrunk, so some of that leaks into strength numbers.")
    w("3. **Overall vs. map-specific.** Ash's list is overall. Many disagreements shrink in specific "
      "modes (flagged in the table above).")
    w("4. **Thin data** for a few niche brawlers (< 500 games; flagged). Shrinkage keeps their estimates "
      "moderate, but they're still noisy.")
    w("")
    w("What this means for the engine: its recommendations follow post-patch Legendary+ results, not "
      "reputation. Expect it to fade nerfed and freshly reworked brawlers and to like some niche picks. "
      "Treat a niche pick's edge with caution if you're not comfortable on that brawler. Personal mode helps "
      "here, and the selection-effect bias is a known limitation (see STATUS.md).\n")

    def row(b):
        bid = by_name[b]
        modes = {mo: mode_tier[mo][b] for mo in mode_tier}
        best_mo = max(modes, key=lambda mo: TVAL[modes[mo]])
        worst_mo = min(modes, key=lambda mo: TVAL[modes[mo]])
        thin = games[bid] < THIN_GAMES
        mode_ok = [MODE_NAMES[mo] for mo in modes if abs(TVAL[modes[mo]] - TVAL[ash[b]["tier"]]) <= 1]
        label = "likely thin data" if thin else "data disagrees"
        if not thin and mode_ok:
            label += f" overall (but matches Ash within 1 tier in {', '.join(mode_ok)})"
        return (f"| {b} | {ash[b]['tier']} | {our_tier[b]} | {25 * ours[b]:+.1f}% | {games[bid]:,} | "
                f"{100 * wr[b]:.1f}% | {100 * pr[b]:.1f}% | {MODE_NAMES[best_mo]} {modes[best_mo]} / "
                f"{MODE_NAMES[worst_mo]} {modes[worst_mo]} | {ash[b]['arrow'] or '-'} | {label} |")

    hdr = ("| brawler | Ash | ours | our strength | games | win rate | pick rate | best / worst mode (our tier) "
           "| Ash arrow | label |\n|---|---|---|---|---|---|---|---|---|---|")
    w(f"## Big disagreements (2+ tiers apart): {len(big)} brawlers\n")
    w(f"\"Likely thin data\" = fewer than {THIN_GAMES} Legendary+ post-patch games. Win rate is raw (not "
      "adjusted for comps); pick rate = share of games the brawler appears in. Ash's list is "
      "overall, so a brawler can legitimately be much better or worse on specific modes. Those cases are "
      "flagged, not treated as errors.\n")
    w("**We rate higher than Ash:**\n")
    w(hdr)
    for b in sorted([b for b in big if TVAL[our_tier[b]] > TVAL[ash[b]["tier"]]], key=lambda b: -ours[b]):
        w(row(b))
    w("\n**We rate lower than Ash:**\n")
    w(hdr)
    for b in sorted([b for b in big if TVAL[our_tier[b]] < TVAL[ash[b]["tier"]]], key=lambda b: ours[b]):
        w(row(b))
    w("")

    w("## Edgar\n")
    e = "Edgar"
    rank = sorted(common, key=lambda b: -ours[b]).index(e) + 1
    w(f"- **Ash: {ash[e]['tier']} tier.** **Ours: {our_tier[e]} tier**, #{rank} of {len(common)} by overall "
      f"strength ({25 * ours[e]:+.1f}%), from {games[by_name[e]]:,} games, {100 * wr[e]:.1f}% raw win rate, "
      f"{100 * pr[e]:.1f}% pick rate.")
    w("- Per mode (our tier): " + ", ".join(f"{MODE_NAMES[mo]} {mode_tier[mo][e]}" for mo in sorted(mode_tier)) + ".\n")

    w("## Full comparison by Ash tier\n")
    for t in TIERS:
        bs = sorted([b for b in common if ash[b]["tier"] == t], key=lambda b: -ours[b])
        w(f"- **{t}** ({len(bs)}): " + ", ".join(f"{b} ({our_tier[b]})" for b in bs))
    w("")

    w("## Ash's arrows vs the official patch notes\n")
    w("Arrows were read from the image. Each marker sits over the top-right of its icon; this was "
      "calibrated on the six brawlers the notes give new Buffies, which all carry rainbow arrows. Notes "
      "source: [Release Notes November 2026](https://supercell.com/en/games/brawlstars/blog/game-updates/release-notes-november-2026/).\n")
    w("| patch-notes category | brawler → Ash's arrow |\n|---|---|")
    for cat, bs in PATCH_NOTES.items():
        w(f"| {cat} | " + ", ".join(f"{b} → {ash[b]['arrow'] or 'none'}" if b in ash else f"{b} → (not listed)" for b in bs) + " |")
    changed = set(sum((v for k, v in PATCH_NOTES.items() if k != "brawl arena only"), []))
    arena = set(PATCH_NOTES["brawl arena only"])
    extra = [(b, ash[b]["arrow"]) for b in ash if ash[b]["arrow"] and b not in changed]
    w("\nArrows on brawlers with **no global change** in the notes: " +
      ", ".join(f"{b} ({a}{', arena-only change' if b in arena else ''})" for b, a in extra) + ".\n")
    w("Interpretation:")
    w("- Rainbow lines up with patch upgrades: all 6 new-Buffie reworks, Vince's new Hypercharge, and "
      "buffs to Shelly, Draco, Hank, Chuck, Melodie and Squeak.")
    w("- Red is on 8 of the 12 nerfed brawlers. Amber, Wendy, Rico and Pierce have no arrow.")
    w("- Green or rainbow is on 9 of the 10 buffed brawlers. Buster has no arrow.")
    w("- But arrows also mark unchanged brawlers (e.g. El Primo, Colt, Mortis, Kaze, Bolt red; Ruffs, "
      "Meeple, Penny, Crow green). So the arrows look like **tier movement since Ash's previous list** "
      "(partly patch-driven), not a strict buff/nerf legend.")
    w("- `patch.json` keeps the official notes as the source of truth for \"changed brawlers\". Nothing "
      "in the image contradicts the notes, so no change is needed there.")
    (ROOT / "reference" / "SANITY_CHECK.md").write_text("\n".join(L) + "\n")
    print(f"rho={rho:.2f} wr={rho_wr:.2f} pr={rho_pr:.2f} big={len(big)} modes={ {k: round(v, 2) for k, v in rho_by_mode.items()} }")


if __name__ == "__main__":
    main()
